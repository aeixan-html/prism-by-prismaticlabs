export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}

export function getDiscountPercent(p: Product): number {
  if (p.mrp <= 0) return 0;
  return Math.round(((p.mrp - p.currentPrice) / p.mrp) * 100);
}

export function getMemberSavings(p: Product): number {
  return p.currentPrice - p.memberPrice;
}

export function getTotalSavings(p: Product): number {
  return p.mrp - p.memberPrice;
}

export function getPriceTrend(p: Product): 'down' | 'up' | 'stable' {
  if (p.currentPrice < p.previousPrice) return 'down';
  if (p.currentPrice > p.previousPrice) return 'up';
  return 'stable';
}
